#include<iostream>

using namespace std;
int main(){

    // FOR LOOP

     int i;
     for(i=0;i<=40;i++){
         cout<<i<<endl;
     }

    // WHILE LOOP

     int y=0;
     while(y<=10){
         cout<<y<<endl;
         y++;
     }

    // DO WHILE LOOP

     int z=0;
     do{
         cout<<z<<endl;
         z++;
     }while(z<=10);

// TABLE OF 6

int a=6,b;
for(b=1;b<=10;b++){
    cout<<a*b<<endl;
}


    return 0;
}